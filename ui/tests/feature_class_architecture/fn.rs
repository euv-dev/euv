#[test]
fn production_views_do_not_choose_cargo_theme_styles() {
    let output: Output = Command::new("python3")
        .arg(
            Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/feature_class_architecture/check.py"),
        )
        .output()
        .expect("Python architecture checker");
    assert!(
        output.status.success(),
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}
