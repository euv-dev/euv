/// The HTTP method name for a `GET` request.
pub(crate) const METHOD_GET: &str = "GET";

/// The HTTP method name for a `POST` request.
pub(crate) const METHOD_POST: &str = "POST";

/// The HTTP method name for a `PUT` request.
pub(crate) const METHOD_PUT: &str = "PUT";

/// The HTTP method name for a `DELETE` request.
pub(crate) const METHOD_DELETE: &str = "DELETE";

/// The property a JavaScript exception carries its name in.
pub(crate) const ERROR_NAME: &str = "name";

/// The name used when the browser raised something without a name.
pub(crate) const UNKNOWN_ERROR: &str = "unknown";

/// The message used when the page has no window to fetch from.
pub(crate) const NOWINDOW: &str = "no window";
